// taa_inject.m — runtime Metal interception PoC.
//
// Loaded with DYLD_INSERT_LIBRARIES. Nothing in the target binary is patched;
// everything happens by swizzling Objective-C methods at load time:
//
//   CAMetalLayer  -setDrawableSize:  remember the size the game asked for
//                 -drawableSize      report that size back to the game
//                 -nextDrawable      hand the game a proxy drawable whose
//                                    texture is our offscreen render target
//   MTLCommandBuffer -presentDrawable:(atTime:|afterMinimumDuration:)
//                                    when given a proxy: append TAA-lite +
//                                    MetalFX spatial upscale + copy into the
//                                    real drawable, then present the real one
//
// The game renders at the size it chose (e.g. 1080p in its own settings) and
// the real CAMetalLayer drawable is resized to the output size (native or
// 3840x2160), so the upscale happens at the very end of the frame.
//
// See README.md: this is an unsupported study PoC. Use at your own risk.

