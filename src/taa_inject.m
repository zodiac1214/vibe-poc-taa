static char kStateKey;

static TAALayerState *existingState(CAMetalLayer *layer) {
    return objc_getAssociatedObject(layer, &kStateKey);
}

static TAALayerState *stateFor(CAMetalLayer *layer) {
    TAALayerState *st = existingState(layer);
    if (st) return st;
    @synchronized(layer) {
        st = existingState(layer);
        if (!st) {
            st = [TAALayerState new];
            objc_setAssociatedObject(layer, &kStateKey, st, OBJC_ASSOCIATION_RETAIN_NONATOMIC);
        }
        return st;
    }
}

