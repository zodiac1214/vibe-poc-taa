#pragma mark - Size bookkeeping

// Decide render/output sizes for this layer and make the real drawable match.
static void syncLayer(CAMetalLayer *layer, TAALayerState *st) {
    @synchronized(st) {
        CGSize current = orig_drawableSize(layer, @selector(drawableSize));
        if (!st->hasRequested) {
            st->hasRequested = YES;
            st->requested = current;
        }
        CGSize req = roundSize(st->requested);

        CGFloat scale = layer.contentsScale > 0 ? layer.contentsScale : 1.0;
        CGSize native = roundSize(CGSizeMake(layer.bounds.size.width * scale, layer.bounds.size.height * scale));
        if (layer.bounds.size.width < 1 || layer.bounds.size.height < 1) native = req;

        CGSize render = roundSize(CGSizeMake(req.width * gCfg.renderScale, req.height * gCfg.renderScale));
        CGSize out = gCfg.outputNative ? native : gCfg.outputSize;
        if (!gCfg.upscale) out = render;

        BOOL active = gCfg.enabled && (gCfg.temporal || !CGSizeEqualToSize(render, out));
        if (!active) render = out = req;

        st->renderSize = render;
        st->outSize = out;
        st->reportSize = render;
        st->active = active;

        CGSize realTarget = active ? out : req;
        if (!CGSizeEqualToSize(current, realTarget)) {
            TAALog(@"layer %p: game=%@ render=%@ output=%@ %@", layer, sz(req), sz(render), sz(out),
                   active ? @"(active)" : @"(passthrough)");
            orig_setDrawableSize(layer, @selector(setDrawableSize:), realTarget);
        }
    }
}

#pragma mark - Resources

static id<MTLTexture> makeTex(id<MTLDevice> dev, MTLPixelFormat f, CGSize s, MTLTextureUsage u, NSString *label) {
    MTLTextureDescriptor *d = [MTLTextureDescriptor texture2DDescriptorWithPixelFormat:f
                                                                                 width:(NSUInteger)s.width
                                                                                height:(NSUInteger)s.height
                                                                             mipmapped:NO];
    d.usage = u;
    d.storageMode = MTLStorageModePrivate;
    id<MTLTexture> t = [dev newTextureWithDescriptor:d];
    t.label = label;
    return t;
}

static BOOL prepareResources(TAALayerState *st, CAMetalLayer *layer) {
    id<MTLDevice> dev = layer.device;
    if (!dev) return NO;
    MTLPixelFormat fmt = layer.pixelFormat;
    if (st->built && st->builtDevice == dev && st->builtFmt == fmt && CGSizeEqualToSize(st->builtRender, st->renderSize) &&
        CGSizeEqualToSize(st->builtOut, st->outSize)) {
        return st->renderTex != nil;
    }

    st->built = YES;
    st->builtDevice = dev;
    st->builtFmt = fmt;
    st->builtRender = st->renderSize;
    st->builtOut = st->outSize;
    st->renderTex = st->scaled = nil;
    st->hist[0] = st->hist[1] = nil;
    st->scaler = nil;
    st->historyValid = NO;
    st->fmt = fmt;

    st->gpu = [TAAGPU forDevice:dev];
    if (!st->gpu) return NO;

    CGSize r = st->renderSize, o = st->outSize;
    BOOL needScale = !CGSizeEqualToSize(r, o);
    MTLPixelFormat scalerIn = gCfg.temporal ? MTLPixelFormatRGBA16Float : fmt;

    MTLTextureUsage scalerColorUsage = 0, scalerOutUsage = 0;
    if (needScale && o.width >= r.width && o.height >= r.height) {
        if (@available(macOS 13.0, *)) {
            if ([MTLFXSpatialScalerDescriptor supportsDevice:dev]) {
                MTLFXSpatialScalerDescriptor *d = [MTLFXSpatialScalerDescriptor new];
                d.inputWidth = (NSUInteger)r.width;
                d.inputHeight = (NSUInteger)r.height;
                d.outputWidth = (NSUInteger)o.width;
                d.outputHeight = (NSUInteger)o.height;
                d.colorTextureFormat = scalerIn;
                d.outputTextureFormat = MTLPixelFormatRGBA16Float;
                BOOL linearData = isSRGB(fmt) || isFloat(fmt);  // shader reads of these give linear values
                d.colorProcessingMode = isFloat(fmt)  ? MTLFXSpatialScalerColorProcessingModeHDR
                                        : linearData ? MTLFXSpatialScalerColorProcessingModeLinear
                                                     : MTLFXSpatialScalerColorProcessingModePerceptual;
                id<MTLFXSpatialScaler> sc = [d newSpatialScalerWithDevice:dev];
                if (sc) {
                    st->scaler = sc;
                    scalerColorUsage = sc.colorTextureUsage;
                    scalerOutUsage = sc.outputTextureUsage;
                }
            }
        }
        if (!st->scaler) TAAWarn(@"MetalFX spatial scaler unavailable, falling back to bilinear");
    }

    MTLTextureUsage ru = MTLTextureUsageRenderTarget | MTLTextureUsageShaderRead | MTLTextureUsagePixelFormatView;
    if (!isSRGB(fmt)) ru |= MTLTextureUsageShaderWrite;  // some engines write the backbuffer from compute
    if (st->scaler && !gCfg.temporal) ru |= scalerColorUsage;
    st->renderTex = makeTex(dev, fmt, r, ru, @"taa-render (game backbuffer)");

    if (gCfg.temporal) {
        MTLTextureUsage hu = MTLTextureUsageRenderTarget | MTLTextureUsageShaderRead | scalerColorUsage;
        st->hist[0] = makeTex(dev, MTLPixelFormatRGBA16Float, r, hu, @"taa-history-0");
        st->hist[1] = makeTex(dev, MTLPixelFormatRGBA16Float, r, hu, @"taa-history-1");
    }
    if (st->scaler) {
        st->scaled = makeTex(dev, MTLPixelFormatRGBA16Float, o, scalerOutUsage | MTLTextureUsageShaderRead, @"taa-upscaled");
    }

    BOOL ok = st->renderTex && (!gCfg.temporal || (st->hist[0] && st->hist[1])) && (!st->scaler || st->scaled);
    if (!ok) {
        TAAWarn(@"failed to allocate textures, passing through");
        st->renderTex = nil;
        return NO;
    }
    TAALog(@"built resources: fmt=%lu render=%@ out=%@ temporal=%d upscaler=%@", (unsigned long)fmt, sz(r), sz(o),
           gCfg.temporal, st->scaler ? @"MetalFX spatial" : (needScale ? @"bilinear" : @"none"));
    return YES;
}

#pragma mark - Encoding

static BOOL drawFullscreen(id<MTLCommandBuffer> cb, id<MTLTexture> dst, id<MTLRenderPipelineState> pso,
                           NSArray<id<MTLTexture>> *srcs, id<MTLSamplerState> smp, const void *bytes, NSUInteger len,
                           NSString *label) {
    if (!pso || !dst) return NO;
    MTLRenderPassDescriptor *rp = [MTLRenderPassDescriptor renderPassDescriptor];
    rp.colorAttachments[0].texture = dst;
    rp.colorAttachments[0].loadAction = MTLLoadActionDontCare;
    rp.colorAttachments[0].storeAction = MTLStoreActionStore;
    id<MTLRenderCommandEncoder> enc = [cb renderCommandEncoderWithDescriptor:rp];
    enc.label = label;
    [enc setRenderPipelineState:pso];
    for (NSUInteger i = 0; i < srcs.count; i++) [enc setFragmentTexture:srcs[i] atIndex:i];
    if (smp) [enc setFragmentSamplerState:smp atIndex:0];
    if (bytes) [enc setFragmentBytes:bytes length:len atIndex:0];
    [enc drawPrimitives:MTLPrimitiveTypeTriangle vertexStart:0 vertexCount:3];
    [enc endEncoding];
    return YES;
}

// Render `src` into an RGBA8 texture, read it back and write a PNG once the GPU is done.
static void dumpTexture(TAALayerState *st, id<MTLCommandBuffer> cb, id<MTLTexture> src, BOOL srgb, NSString *path) {
    TAAGPU *g = st->gpu;
    MTLPixelFormat f = srgb ? MTLPixelFormatRGBA8Unorm_sRGB : MTLPixelFormatRGBA8Unorm;
    NSUInteger w = src.width, h = src.height, bpr = w * 4;
    id<MTLTexture> tmp = makeTex(g->device, f, CGSizeMake(w, h), MTLTextureUsageRenderTarget, @"taa-dump");
    id<MTLBuffer> buf = [g->device newBufferWithLength:bpr * h options:MTLResourceStorageModeShared];
    if (!tmp || !buf) return;
    drawFullscreen(cb, tmp, [g copyPSOFor:f], @[ src ], g->linear, NULL, 0, @"taa-dump");
    id<MTLBlitCommandEncoder> bl = [cb blitCommandEncoder];
    [bl copyFromTexture:tmp sourceSlice:0 sourceLevel:0 sourceOrigin:MTLOriginMake(0, 0, 0)
                 sourceSize:MTLSizeMake(w, h, 1) toBuffer:buf destinationOffset:0
        destinationBytesPerRow:bpr destinationBytesPerImage:bpr * h];
    [bl endEncoding];
    [cb addCompletedHandler:^(id<MTLCommandBuffer> done) {
        NSData *data = [NSData dataWithBytes:buf.contents length:bpr * h];
        CGColorSpaceRef cs = CGColorSpaceCreateWithName(kCGColorSpaceSRGB);
        CGDataProviderRef dp = CGDataProviderCreateWithCFData((__bridge CFDataRef)data);
        CGImageRef img = CGImageCreate(w, h, 8, 32, bpr, cs, kCGImageAlphaNoneSkipLast | kCGBitmapByteOrderDefault, dp,
                                       NULL, false, kCGRenderingIntentDefault);
        CGImageDestinationRef d = CGImageDestinationCreateWithURL((__bridge CFURLRef)[NSURL fileURLWithPath:path],
                                                                  CFSTR("public.png"), 1, NULL);
        if (d && img) {
            CGImageDestinationAddImage(d, img, NULL);
            CGImageDestinationFinalize(d);
            fprintf(stderr, "[taa-inject] dumped %s (%lux%lu)\n", path.UTF8String, (unsigned long)w, (unsigned long)h);
        }
        if (d) CFRelease(d);
        if (img) CGImageRelease(img);
        CGDataProviderRelease(dp);
        CGColorSpaceRelease(cs);
    }];
}

// Append our passes to `cb`: game backbuffer -> TAA-lite -> MetalFX -> real drawable.
static BOOL encodeResolve(TAALayerState *st, id<CAMetalDrawable> real, id<MTLCommandBuffer> cb) {
    @synchronized(st) {
        TAAGPU *g = st->gpu;
        id<MTLTexture> dst = real.texture;
        id<MTLTexture> src = st->renderTex;
        if (!g || !dst || !src) return NO;
        st->frame++;
        BOOL dump = gCfg.dumpFrame > 0 && st->frame == gCfg.dumpFrame;
        // Shader reads of sRGB/float formats return linear values; write the dump as sRGB then.
        BOOL linearData = isSRGB(st->fmt) || isFloat(st->fmt);
        if (dump) {
            dumpTexture(st, cb, src, linearData, [gCfg.dumpPrefix stringByAppendingString:@"_input.png"]);
        }

        if (gCfg.temporal) {
            int cur = st->histIdx ^ 1;
            struct {
                float blend, clampGamma;
                uint32_t reset, pad;
            } params = {gCfg.blend, gCfg.clampGamma, st->historyValid ? 0u : 1u, 0u};
            drawFullscreen(cb, st->hist[cur], g->taaPSO, @[ src, st->hist[st->histIdx] ], nil, &params, sizeof params,
                           @"taa-resolve");
            st->histIdx = cur;
            st->historyValid = YES;
            src = st->hist[cur];
        }

        if (st->scaler) {
            if (@available(macOS 13.0, *)) {
                id<MTLFXSpatialScaler> sc = st->scaler;
                sc.colorTexture = src;
                sc.outputTexture = st->scaled;
                sc.inputContentWidth = src.width;
                sc.inputContentHeight = src.height;
                [sc encodeToCommandBuffer:cb];
                src = st->scaled;
            }
        }

        // Always finish with a render pass: works with framebufferOnly drawables and
        // handles any size/format difference (bilinear when MetalFX was not used).
        BOOL ok = drawFullscreen(cb, dst, [g copyPSOFor:dst.pixelFormat], @[ src ], g->linear, NULL, 0, @"taa-present");
        if (dump) {
            dumpTexture(st, cb, src, linearData, [gCfg.dumpPrefix stringByAppendingString:@"_output.png"]);
        }
        return ok;
    }
}

#pragma mark - Proxy drawable

@interface TAAProxyDrawable : NSProxy <CAMetalDrawable> {
  @public
    id<CAMetalDrawable> real;
    TAALayerState *state;
    BOOL encoded;
}
@end

@implementation TAAProxyDrawable

- (id<MTLTexture>)texture { return state->renderTex; }
- (CAMetalLayer *)layer { return real.layer; }
- (CFTimeInterval)presentedTime { return real.presentedTime; }
- (NSUInteger)drawableID { return real.drawableID; }
- (void)addPresentedHandler:(MTLDrawablePresentedHandler)block { [real addPresentedHandler:block]; }

// Called by our command-buffer hooks. Returns the real drawable to present.
- (id<CAMetalDrawable>)resolveInto:(id<MTLCommandBuffer>)cb {
    if (!encoded) {
        encoded = YES;
        encodeResolve(state, real, cb);
    }
    return real;
}

// Direct -present (e.g. from a scheduled handler). We have no access to the game's
// command buffer here, so we submit on our own queue. Cross-queue ordering with the
// game's rendering is NOT guaranteed — best effort only.
- (void)presentWith:(void (^)(id<MTLCommandBuffer> cb))presentBlock {
    if (encoded) {
        [real present];
        return;
    }
    if (!state->warnedDirect) {
        state->warnedDirect = YES;
        TAAWarn(@"game calls -[CAMetalDrawable present] directly; using own queue (ordering is best effort)");
    }
    id<MTLCommandBuffer> cb = [state->gpu->queue commandBuffer];
    [self resolveInto:cb];
    presentBlock(cb);
    [cb commit];
}

- (void)present {
    id<CAMetalDrawable> r = real;
    [self presentWith:^(id<MTLCommandBuffer> cb) { [cb presentDrawable:r]; }];
}

- (void)presentAtTime:(CFTimeInterval)t {
    id<CAMetalDrawable> r = real;
    [self presentWith:^(id<MTLCommandBuffer> cb) { [cb presentDrawable:r atTime:t]; }];
}

- (void)presentAfterMinimumDuration:(CFTimeInterval)d {
    id<CAMetalDrawable> r = real;
    [self presentWith:^(id<MTLCommandBuffer> cb) { [cb presentDrawable:r afterMinimumDuration:d]; }];
}

// Everything else goes to the real drawable.
- (id)forwardingTargetForSelector:(SEL)sel { return real; }
- (NSMethodSignature *)methodSignatureForSelector:(SEL)sel {
