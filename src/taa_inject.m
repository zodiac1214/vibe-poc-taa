@end

#pragma mark - Hooks

static void hk_setDrawableSize(CAMetalLayer *self, SEL _cmd, CGSize s) {
    TAALayerState *st = stateFor(self);
    @synchronized(st) {
        st->hasRequested = YES;
        st->requested = s;
    }
    syncLayer(self, st);
}

static CGSize hk_drawableSize(CAMetalLayer *self, SEL _cmd) {
    TAALayerState *st = existingState(self);
    if (!st || !st->hasRequested) return orig_drawableSize(self, _cmd);
    return st->reportSize;
}

static void hk_presentDrawable(id self, SEL _cmd, id d) {
    if (d && object_getClass(d) == gProxyClass) d = [(TAAProxyDrawable *)d resolveInto:self];
    orig_presentDrawable(self, _cmd, d);
}

static void hk_presentDrawableAtTime(id self, SEL _cmd, id d, CFTimeInterval t) {
    if (d && object_getClass(d) == gProxyClass) d = [(TAAProxyDrawable *)d resolveInto:self];
    orig_presentDrawableAtTime(self, _cmd, d, t);
}

static void hk_presentDrawableAfter(id self, SEL _cmd, id d, CFTimeInterval t) {
    if (d && object_getClass(d) == gProxyClass) d = [(TAAProxyDrawable *)d resolveInto:self];
    orig_presentDrawableAfter(self, _cmd, d, t);
}

static IMP swap(Class cls, SEL sel, IMP replacement) {
    Method m = class_getInstanceMethod(cls, sel);
    if (!m) {
        TAAWarn([NSString stringWithFormat:@"-[%s %s] not found", class_getName(cls), sel_getName(sel)]);
        return NULL;
    }
    return method_setImplementation(m, replacement);
}

// The concrete command buffer class is private and GPU-specific (e.g. AGX...CommandBuffer),
// so discover it from a real instance created on the game's device.
static BOOL installCommandBufferHooks(id<MTLDevice> dev) {
    static dispatch_once_t once;
    static BOOL ok;
    dispatch_once(&once, ^{
        id<MTLCommandQueue> q = [dev newCommandQueue];
        id<MTLCommandBuffer> probe = [q commandBuffer];
        Class cls = object_getClass(probe);
        orig_presentDrawable = (PresentFn)swap(cls, @selector(presentDrawable:), (IMP)hk_presentDrawable);
        orig_presentDrawableAtTime =
            (PresentTimeFn)swap(cls, @selector(presentDrawable:atTime:), (IMP)hk_presentDrawableAtTime);
        orig_presentDrawableAfter =
            (PresentTimeFn)swap(cls, @selector(presentDrawable:afterMinimumDuration:), (IMP)hk_presentDrawableAfter);
        ok = orig_presentDrawable && orig_presentDrawableAtTime && orig_presentDrawableAfter;
        TAALog(@"command buffer class %s hooked: %@", class_getName(cls), ok ? @"yes" : @"NO");
    });
    return ok;
}

static id hk_nextDrawable(CAMetalLayer *self, SEL _cmd) {
    TAALayerState *st = stateFor(self);
    syncLayer(self, st);
    id<CAMetalDrawable> real = orig_nextDrawable(self, _cmd);
    if (!real || !st->active) return real;
    if (!installCommandBufferHooks(self.device)) return real;
    BOOL ready;
    @synchronized(st) {
        ready = prepareResources(st, self);
    }
    if (!ready) return real;
    TAAProxyDrawable *p = [TAAProxyDrawable alloc];
    p->real = real;
    p->state = st;
    return p;
}

__attribute__((constructor)) static void taa_inject_init(void) {
    @autoreleasepool {
        loadConfig();
        fprintf(stderr, "[taa-inject] loaded (unsupported study PoC, use at your own risk). enabled=%d temporal=%d "
                        "upscale=%d output=%s render_scale=%.2f\n",
                gCfg.enabled, gCfg.temporal, gCfg.upscale,
                gCfg.outputNative ? "native" : sz(gCfg.outputSize).UTF8String, gCfg.renderScale);
        if (!gCfg.enabled) return;
        gProxyClass = [TAAProxyDrawable class];
        Class layer = [CAMetalLayer class];
        orig_nextDrawable = (NextDrawableFn)swap(layer, @selector(nextDrawable), (IMP)hk_nextDrawable);
        orig_setDrawableSize = (SetSizeFn)swap(layer, @selector(setDrawableSize:), (IMP)hk_setDrawableSize);
        orig_drawableSize = (GetSizeFn)swap(layer, @selector(drawableSize), (IMP)hk_drawableSize);
        if (!orig_nextDrawable || !orig_setDrawableSize || !orig_drawableSize) {
            TAAWarn(@"CAMetalLayer hooks incomplete; behaviour undefined");
        }
    }
}
