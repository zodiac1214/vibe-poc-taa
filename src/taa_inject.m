@interface TAAGPU : NSObject {
  @public
    id<MTLDevice> device;
    id<MTLCommandQueue> queue;
    id<MTLLibrary> library;
    id<MTLRenderPipelineState> taaPSO;  // writes RGBA16Float history
    id<MTLSamplerState> linear;
    NSMutableDictionary<NSNumber *, id<MTLRenderPipelineState>> *copyPSOs;
}
+ (instancetype)forDevice:(id<MTLDevice>)device;
- (id<MTLRenderPipelineState>)copyPSOFor:(MTLPixelFormat)fmt;
@end

@implementation TAAGPU

+ (instancetype)forDevice:(id<MTLDevice>)device {
    static NSMutableDictionary<NSNumber *, TAAGPU *> *all;
    @synchronized(self) {
        if (!all) all = [NSMutableDictionary new];
        NSNumber *key = @(device.registryID);
        TAAGPU *g = all[key];
        if (!g) {
            g = [[TAAGPU alloc] initWithDevice:device];
            if (g) all[key] = g;
        }
        return g;
    }
}

- (instancetype)initWithDevice:(id<MTLDevice>)dev {
    if (!(self = [super init])) return nil;
    device = dev;
    queue = [dev newCommandQueue];
    queue.label = @"taa-inject";

    NSString *src = [[NSString alloc] initWithBytes:taa_metal length:taa_metal_len encoding:NSUTF8StringEncoding];
    NSError *err = nil;
    library = [dev newLibraryWithSource:src options:nil error:&err];
    if (!library) {
        TAAWarn([NSString stringWithFormat:@"shader compile failed: %@", err]);
        return nil;
    }

    MTLRenderPipelineDescriptor *d = [MTLRenderPipelineDescriptor new];
    d.label = @"taa-resolve";
    d.vertexFunction = [library newFunctionWithName:@"taa_fullscreen_vs"];
    d.fragmentFunction = [library newFunctionWithName:@"taa_resolve_fs"];
    d.colorAttachments[0].pixelFormat = MTLPixelFormatRGBA16Float;
    taaPSO = [dev newRenderPipelineStateWithDescriptor:d error:&err];
    if (!taaPSO) {
        TAAWarn([NSString stringWithFormat:@"TAA pipeline failed: %@", err]);
        return nil;
    }

    MTLSamplerDescriptor *sd = [MTLSamplerDescriptor new];
    sd.minFilter = sd.magFilter = MTLSamplerMinMagFilterLinear;
    sd.sAddressMode = sd.tAddressMode = MTLSamplerAddressModeClampToEdge;
    linear = [dev newSamplerStateWithDescriptor:sd];
    copyPSOs = [NSMutableDictionary new];
    return self;
}

- (id<MTLRenderPipelineState>)copyPSOFor:(MTLPixelFormat)fmt {
    @synchronized(self) {
        id<MTLRenderPipelineState> p = copyPSOs[@(fmt)];
        if (p) return p;
        MTLRenderPipelineDescriptor *d = [MTLRenderPipelineDescriptor new];
        d.label = @"taa-copy";
        d.vertexFunction = [library newFunctionWithName:@"taa_fullscreen_vs"];
        d.fragmentFunction = [library newFunctionWithName:@"taa_copy_fs"];
        d.colorAttachments[0].pixelFormat = fmt;
        NSError *err = nil;
        p = [device newRenderPipelineStateWithDescriptor:d error:&err];
        if (!p) {
            TAAWarn([NSString stringWithFormat:@"copy pipeline for format %lu failed: %@", (unsigned long)fmt, err]);
            return nil;
        }
        copyPSOs[@(fmt)] = p;
        return p;
    }
}

@end

