#pragma mark - Config

typedef struct {
    BOOL enabled, temporal, upscale, log;
    BOOL outputNative;
    CGSize outputSize;
    double renderScale;
    float blend, clampGamma;
    long dumpFrame;
    NSString *dumpPrefix;
} TAAConfig;

static TAAConfig gCfg;

static void TAALog(NSString *fmt, ...) NS_FORMAT_FUNCTION(1, 2);
static void TAALog(NSString *fmt, ...) {
    if (!gCfg.log) return;
    va_list ap;
    va_start(ap, fmt);
    NSString *s = [[NSString alloc] initWithFormat:fmt arguments:ap];
    va_end(ap);
    fprintf(stderr, "[taa-inject] %s\n", s.UTF8String);
}

static void TAAWarn(NSString *s) { fprintf(stderr, "[taa-inject] WARNING: %s\n", s.UTF8String); }

static NSString *envStr(const char *k) {
    const char *v = getenv(k);
    return (v && *v) ? @(v) : nil;
}

static BOOL envBool(const char *k, BOOL def) {
    NSString *v = envStr(k).lowercaseString;
    if (!v) return def;
    return !([v isEqualToString:@"0"] || [v isEqualToString:@"false"] || [v isEqualToString:@"off"] ||
             [v isEqualToString:@"no"]);
}

static double envDouble(const char *k, double def, double lo, double hi) {
    NSString *v = envStr(k);
    if (!v) return def;
    double d = v.doubleValue;
    if (!(d >= lo && d <= hi)) {
        TAAWarn([NSString stringWithFormat:@"%s=%@ out of range [%g, %g], using %g", k, v, lo, hi, def]);
        return def;
    }
    return d;
}

static void loadConfig(void) {
    gCfg.log = envBool("TAA_LOG", NO);
    gCfg.enabled = envBool("TAA_ENABLE", YES);
    gCfg.temporal = envBool("TAA_TEMPORAL", YES);
    gCfg.upscale = envBool("TAA_UPSCALE", YES);
    gCfg.renderScale = envDouble("TAA_RENDER_SCALE", 1.0, 0.25, 1.0);
    gCfg.blend = (float)envDouble("TAA_BLEND", 0.1, 0.01, 1.0);
    gCfg.clampGamma = (float)envDouble("TAA_CLAMP", 1.25, 0.25, 8.0);

    NSString *out = envStr("TAA_OUTPUT").lowercaseString ?: @"native";
    gCfg.outputNative = YES;
    int w = 0, h = 0;
    if ([out isEqualToString:@"4k"]) {
        gCfg.outputNative = NO;
        gCfg.outputSize = CGSizeMake(3840, 2160);
    } else if (sscanf(out.UTF8String, "%dx%d", &w, &h) == 2 && w > 0 && h > 0 && w <= 16384 && h <= 16384) {
        gCfg.outputNative = NO;
        gCfg.outputSize = CGSizeMake(w, h);
    } else if (![out isEqualToString:@"native"]) {
        TAAWarn([NSString stringWithFormat:@"TAA_OUTPUT=%@ not understood (native | 4k | WxH), using native", out]);
    }

    gCfg.dumpFrame = envStr("TAA_DUMP_FRAME").integerValue;
    gCfg.dumpPrefix = envStr("TAA_DUMP_PREFIX") ?: @"/tmp/taa_dump";
}

#pragma mark - Helpers

static BOOL isSRGB(MTLPixelFormat f) {
    switch (f) {
        case MTLPixelFormatBGRA8Unorm_sRGB:
        case MTLPixelFormatRGBA8Unorm_sRGB:
        case MTLPixelFormatBGRA10_XR_sRGB:
        case MTLPixelFormatBGR10_XR_sRGB:
            return YES;
        default:
            return NO;
    }
}

static BOOL isFloat(MTLPixelFormat f) {
    return f == MTLPixelFormatRGBA16Float || f == MTLPixelFormatRGBA32Float || f == MTLPixelFormatRG11B10Float;
}

static CGSize roundSize(CGSize s) {
    return CGSizeMake(MAX(1, lround(s.width)), MAX(1, lround(s.height)));
}

static NSString *sz(CGSize s) { return [NSString stringWithFormat:@"%.0fx%.0f", s.width, s.height]; }

